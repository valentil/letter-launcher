// LLF-81: writes assets/cad/aircraft_aero.json — the aero tables the flight model flies on.
// Method (also written into the JSON): wing-section + fuselage build-up on the light_aircraft
// CAD geometry. Lift-curve slope from the NACA 2412 section (Abbott & von Doenhoff) corrected
// to the CAD wing's aspect ratio by lifting-line theory; CLmax / flap increments calibrated so
// the stall speeds match the class's published Vs1 / Vs0; parasite drag from the class's
// published CD0 build-up; cad_wind_tunnel solves on the CAD wing section and fuselage are
// recorded in `cfd` (see there for why lift was not taken from them).
// Run: node tools/cad/gen/aircraft_aero_gen.js
const fs = require('fs'), path = require('path');
const r4 = v => Math.round(v * 10000) / 10000;

const geom = { spanM: 11.0, chordM: 1.5, areaM2: 16.5, aspectRatio: r4(11 * 11 / 16.5), incidenceDeg: 1.5,
    macM: 1.5, massKg: 1043, emptyKg: 767, mtowKg: 1111, iyyKgM2: 1825 };
const e = 0.80;                                   // Oswald factor, rectangular high wing with fuselage
const a0 = 0.105;                                 // NACA 2412 section lift slope, /deg
const alphaL0 = -2.1;                             // NACA 2412 zero-lift angle, deg
const a3d = a0 / (1 + 57.2958 * a0 / (Math.PI * e * geom.aspectRatio));   // lifting line, /deg
const K = 1 / (Math.PI * e * geom.aspectRatio);   // induced drag factor
const CONFIG = {
    0:  { dCL0: 0.00, CLmax: 1.47, dCD0: 0.000, dCm0: 0.000 },   // Vs1 53 kt @ 1111 kg
    10: { dCL0: 0.25, CLmax: 1.62, dCD0: 0.008, dCm0: -0.030 },
    20: { dCL0: 0.45, CLmax: 1.72, dCD0: 0.022, dCm0: -0.060 },
    30: { dCL0: 0.60, CLmax: 1.80, dCD0: 0.042, dCm0: -0.085 }   // Vs0 48 kt @ 1111 kg
};
const CD0 = 0.0270, CD0_gear = 0.0070;            // clean retract airframe; gear-down increment
const AOA = []; for (let a = -4; a <= 18; a += 2) AOA.push(a);

function table(flap) {
    const c = CONFIG[flap];
    const lin = a => a3d * (a + geom.incidenceDeg - alphaL0) + c.dCL0;
    const stallAoA = (c.CLmax - c.dCL0) / a3d - geom.incidenceDeg + alphaL0;
    const CL = [], CD = [], Cm = [];
    AOA.forEach(a => {
        let cl = lin(a), extra = 0, cm = 0.035 + c.dCm0 - 0.0095 * a;   // static stability Cm_alpha -0.54/rad
        const knee = 0.88 * c.CLmax;
        if (cl > knee && a <= stallAoA) cl = knee + (c.CLmax - knee) * Math.sin(Math.min(1, (cl - knee) / (lin(stallAoA) - knee)) * Math.PI / 2);
        if (a > stallAoA) {                       // past the break: lift falls, drag and nose-down moment jump
            const p = a - stallAoA;
            cl = c.CLmax * (1 - 0.32 * Math.min(1, p / 4));
            extra = 0.035 * p;
            cm -= 0.06 + 0.012 * p;
        }
        CL.push(r4(cl)); CD.push(r4(CD0 + c.dCD0 + K * cl * cl + extra)); Cm.push(r4(cm));
    });
    return { CL, CD, Cm, stallAoA: Math.round(stallAoA * 10) / 10, CLmax: c.CLmax };
}
const configs = {}; [0, 10, 20, 30].forEach(f => { configs[f] = table(f); });
const aero = {
    _note: 'Generated by tools/cad/gen/aircraft_aero_gen.js (LLF-81). Body-axis AoA in degrees; coefficients on the CAD wing reference area. Flap 10 is a detent the game uses between the measured/tabulated 0/20/30 sets.',
    model: 'light_aircraft',
    geometry: geom,
    aoaDeg: AOA,
    flaps: configs,
    cd0: { clean: CD0, gearDown: CD0_gear },
    inducedK: r4(K),
    liftSlopePerDeg: r4(a3d),
    controls: { elevatorCmPerDeg: -0.022, pitchServoHz: 0.9, pitchDamping: 0.85 },
    propulsion: { maxPowerW: 134000, propEfficiency: 0.78, staticThrustN: 2400 },
    method: [
        'Geometry: the committed CAD asset assets/cad/light_aircraft.glb (tools/cad/recipes/light_aircraft.json): 11.0 m span, 1.5 m constant-chord NACA 2412 wing (S = 16.5 m^2, AR 7.33), 1.5 deg incidence, aft-25 % flaps and ailerons.',
        'Wing section: NACA 2412 section lift slope 0.105/deg and zero-lift angle -2.1 deg (Abbott & von Doenhoff, Theory of Wing Sections, App. IV, Re 6e6), corrected to the CAD aspect ratio by Prandtl lifting-line a = a0 / (1 + 57.3 a0 / (pi e AR)), e = 0.80 -> ' + r4(a3d) + '/deg.',
        'Stall: CLmax per flap setting calibrated so 1111 kg stalls at the class published Vs1 = 53 kt clean and Vs0 = 48 kt flaps 30 (sea level); the curve rounds over from 88 % CLmax, and past stallAoA lift falls 32 % over 4 deg while drag and nose-down Cm jump (the buffet / nose-drop the sim plays).',
        'Flaps: aft-25 % chord plain/slotted flap increments dCL0 0.25/0.45/0.60 and dCD0 0.008/0.022/0.042 at 10/20/30 deg (Raymer, Aircraft Design 5e, sec. 12.4 flap effectiveness, scaled to the 47 % flapped span of the CAD wing).',
        'Drag: CD = CD0 + K CL^2 + flap dCD0 (+0.007 gear down). CD0 0.027 clean is the class figure for the retractable variant (fixed-gear class ~0.031).',
        'cad_wind_tunnel: run on the CAD wing section and fuselage (results in `cfd`). The MAC-grid solver could only be run at 2-4 cells across the 180 mm wing thickness inside the 60 s device-relay window (effective Re 500-2000, solver flags it diffusion-dominated), which does not resolve circulation lift: the section returned Cl ~ 0 at 4 deg. Its lift was therefore NOT used; the tunnel numbers are kept as provenance and as a drag sanity check only.'
    ],
    cfd: []
};
const out = path.join(__dirname, '..', '..', '..', 'assets', 'cad', 'aircraft_aero.json');
if (require.main === module) {
    let prev = null; try { prev = JSON.parse(fs.readFileSync(out, 'utf8')); } catch (_) { }
    if (prev && prev.cfd) aero.cfd = prev.cfd;   // keep recorded tunnel runs
    fs.writeFileSync(out, JSON.stringify(aero, null, 2).replace(/\n/g, '\r\n') + '\r\n');
    [0, 10, 20, 30].forEach(f => {
        const c = configs[f], vs = Math.sqrt(2 * 1111 * 9.81 / (1.225 * geom.areaM2 * c.CLmax));
        console.log('flaps', f, 'stallAoA', c.stallAoA, 'Vs(1111kg)', (vs / 0.5144).toFixed(1), 'kt', 'CL', c.CL.join(' '));
    });
}
module.exports = { aero };
