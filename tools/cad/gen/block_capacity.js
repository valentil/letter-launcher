#!/usr/bin/env node
// tools/cad/gen/block_capacity.js (LLF-85) - writes assets/cad/block_capacity.json: the allowable load of each
// TOWER BUILD block type, from the CAD masses/sections in assets/cad/manifest.d/tower_block.json and tower_beam.json.
//
// METHOD: analytic. The NativeCAD server on this machine reports `capability_missing: fea` (no CalculiX), so
// cad_fea_case/cad_fea_run could not be used. For prismatic members under uniform end pressure, the FEA answer is the
// closed-form one (sigma = P/A, bottom face fixed) except for end effects, so the capacities below are the hand
// calculations FEA would be checked against:
//   concrete / brick  allowable bearing = phi * 0.85 * f'c(or f'm) * net section area   (ACI 318-19 22.8 bearing, phi 0.65)
//   steel column      phi * Fcr * Ag, AISC 360-16 E3 flexural buckling (phi 0.9, K = 1.0, KL/r from ry)
//   axial stiffness   k = E * A / L           (feeds the impact force  F = v * sqrt(k_eff * m), k_eff = k and the bed in series)
// If a CalculiX host is available later, re-run cad_fea_case on tower_block / tower_beam (fixed bottom, pressure on top)
// and compare `capacityN / netAreaM2` with yield_stress x SF from results.json; the runtime only reads this JSON.
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..', '..');
const man = n => JSON.parse(fs.readFileSync(path.join(ROOT, 'assets/cad/manifest.d', n + '.json'), 'utf8'));
const mp = n => JSON.parse(fs.readFileSync(path.join(ROOT, 'tools/cad/massprops', n + '.json'), 'utf8'));
const blk = man('tower_block'), beam = man('tower_beam'), bm = mp('tower_block'), wm = mp('tower_beam');
const G = 9.80665, r = (x, d) => { const k = Math.pow(10, d == null ? 3 : d); return Math.round(x * k) / k; };

const blockVolM3 = bm.block.volumeMm3 / 1e9, H = blk.bboxM.size[1], footprint = blk.bboxM.size[0] * blk.bboxM.size[2];
const netArea = blockVolM3 / H;                                     // 3.0 m^2: cored section is 75 % of 2 x 2
const concrete = { fc: 30e6, E: 30e9, density: 2400, phi: 0.65 };
const brick = { fm: 20e6, E: 12e9, density: 1800, phi: 0.65 };      // clay masonry unit, ASTM C62 grade SW >= 20.7 MPa avg (assumed 20)
const steel = { Fy: 345e6, E: 200e9, phi: 0.9 };                    // ASTM A992
const Ag = wm.w_section.volumeMm3 / 1.2e3 / 1e6;                    // m^2 from CAD volume / 1.2 m
const ry = 0.0947, KL = 1.2;                                        // W14x90 ry = 3.73 in (AISC), pinned-pinned
const Fe = Math.PI * Math.PI * steel.E / Math.pow(KL / ry, 2), Fcr = Math.pow(0.658, steel.Fy / Fe) * steel.Fy;

const types = {
    CONCRETE: {
        asset: 'tower_block', material: 'concrete C30', massKg: r(blk.massKg, 1), footprintM2: footprint, netAreaM2: r(netArea),
        sizeM: [2.0, 1.3, 2.0], strengthPa: concrete.fc, allowableStressPa: r(concrete.phi * 0.85 * concrete.fc, 0),
        capacityN: r(concrete.phi * 0.85 * concrete.fc * netArea, 0), youngsPa: concrete.E, axialStiffnessNPerM: r(concrete.E * netArea / H, 0),
        areaExponent: 1.0, ductility: 1.0, failure: 'crushing',
        basis: 'phi 0.65 x 0.85 f\'c 30 MPa on the 3.0 m^2 cored section (ACI 318-19 22.8)'
    },
    BRICK: {
        asset: 'tower_block', material: 'clay masonry', massKg: r(blockVolM3 * brick.density, 1), footprintM2: footprint, netAreaM2: r(netArea),
        sizeM: [2.0, 1.3, 2.0], strengthPa: brick.fm, allowableStressPa: r(brick.phi * 0.85 * brick.fm, 0),
        capacityN: r(brick.phi * 0.85 * brick.fm * netArea, 0), youngsPa: brick.E, axialStiffnessNPerM: r(brick.E * netArea / H, 0),
        areaExponent: 1.0, ductility: 1.0, failure: 'crushing',
        basis: 'same cored geometry as tower_block (tinted), clay density 1800 kg/m^3, f\'m 20 MPa, phi 0.65 x 0.85'
    },
    STEEL: {
        asset: 'tower_beam', material: 'ASTM A992 W14x90 column on 50 mm plates', massKg: r(beam.massKg, 1), footprintM2: r(1.7 * 1.7), netAreaM2: r(Ag, 5),
        sizeM: [1.7, 1.3, 1.7], strengthPa: steel.Fy, allowableStressPa: r(steel.phi * Fcr, 0),
        capacityN: r(steel.phi * Fcr * Ag, 0), youngsPa: steel.E, axialStiffnessNPerM: r(steel.E * Ag / 1.2, 0),
        areaExponent: 0.5, ductility: 6, failure: 'yield / buckling',
        basis: 'phi 0.9 x Fcr x Ag, AISC 360-16 E3, KL/r = ' + r(KL / ry, 1) + ', Fe ' + r(Fe / 1e9, 1) + ' GPa; the cap plates spread an overhung load (area exponent 0.5); ductility 6 lets the column absorb impact energy plastically (impactDuctilityFactor = sqrt(2*6-1))'
    }
};
Object.keys(types).forEach(k => { types[k].impactDuctilityFactor = r(Math.sqrt(2 * types[k].ductility - 1), 3); });

const out = {
    _comment: 'Generated by tools/cad/gen/block_capacity.js - do not hand edit. Allowable load of one block before it cracks, per type.',
    method: 'analytic (ACI 318 bearing, AISC 360 E3); NativeCAD cad_fea_run was unavailable (capability_missing: fea)',
    fea: { available: false, reason: 'cad_fea_case returned capability_missing: no CalculiX solver installed on the NativeCAD host', recipe: 'cad_fea_case {fixed: bottom face, pressure 10 MPa: top face}, material per type; capacity = yield / (sigma at that pressure) x pressure x netArea' },
    gravity: G,
    bedStiffnessNPerM: 5e8,
    bedNote: 'sand / mortar bedding under a landing block (assumed); impact force F = v * sqrt(k_eff * m) with k_eff = 1/(1/k_axial + 1/k_bed), divided by the type ductility factor',
    types
};
fs.writeFileSync(path.join(ROOT, 'assets/cad/block_capacity.json'), JSON.stringify(out, null, 2).replace(/\n/g, '\r\n') + '\r\n');
Object.keys(types).forEach(k => console.log(k, 'mass', types[k].massKg, 'cap MN', r(types[k].capacityN / 1e6, 2), 'k', types[k].axialStiffnessNPerM.toExponential(2)));
